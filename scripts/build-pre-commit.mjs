#!/usr/bin/env node
/**
 * Build the CLI that the pre-commit hooks run, `integrations/pre-commit/cli.mjs`.
 *
 * pre-commit installs a hook from this repository's source at a tag, where the
 * compiled `dist/` is not committed and no build runs. So the hooks run one
 * committed file with every dependency inlined. It finds the repository's
 * `package.json` and `rules/default.yml` two folders up, as `dist/cli.js` does
 * from `src/`. Until ADR-008 this was the Claude Code plugin's bundled CLI.
 *
 * Runs as part of `npm run build`. Pass --check to fail when the committed
 * file differs from a fresh build, as CI's drift job does for generated files.
 */

import { build } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(root, "dist", "cli.js");
const out = resolve(root, "integrations", "pre-commit", "cli.mjs");
const HEADER = "// GENERATED by scripts/build-pre-commit.mjs from dist/cli.js. Do not edit.\n";

export async function bundlePreCommit() {
  if (!existsSync(entry)) throw new Error("dist/cli.js is missing. Run `tsc -p tsconfig.json` first.");
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    outfile: out,
    platform: "node",
    format: "esm",
    target: "node20",
    minify: false,
    legalComments: "none",
    // Bundled CommonJS libraries call `require` for Node's own modules.
    banner: { js: "import { createRequire as __createRequire } from 'node:module';\nconst require = __createRequire(import.meta.url);" },
    absWorkingDir: root,
    logLevel: "silent",
  });
  const text = result.outputFiles[0].text;
  // The `#!` line must stay first.
  if (!text.startsWith("#!")) return HEADER + text;
  const firstLine = text.indexOf("\n") + 1;
  return text.slice(0, firstLine) + HEADER + text.slice(firstLine);
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const text = await bundlePreCommit();
  const current = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (process.argv.includes("--check")) {
    if (current !== text) {
      process.stderr.write("plain-english: integrations/pre-commit/cli.mjs is stale. Run `npm run build` and commit it.\n");
      process.exit(1);
    }
    process.stdout.write("pre-commit: bundle matches the working tree\n");
  } else {
    if (current !== text) writeFileSync(out, text, "utf8");
    process.stdout.write(`pre-commit: ${current === text ? "unchanged" : "wrote"} integrations/pre-commit/cli.mjs (${Math.round(Buffer.byteLength(text) / 1024)} KB)\n`);
  }
}
