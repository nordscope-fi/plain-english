/**
 * Claude Code.
 *
 * The reference profile, and the one the other three are shaped like. Its
 * PreToolUse contract became the de-facto standard by being copied: Copilot
 * ships a compatibility mode that reads these exact field names, Codex and
 * Factory Droid use the same `permissionDecision` vocabulary, and Continue CLI
 * reads `.claude/settings.json` directly.
 *
 * Docs: https://code.claude.com/docs/en/hooks
 */

import type { Decision } from "../adapters/hook.ts";
import type { AgentProfile, HookEvent, NormalisedEvent, PlanContext } from "./profile.ts";
import { asRecord, issueFields, pick, pickArray } from "./fields.ts";

const CHANNELS = [
  {
    channel: "docs",
    matcher: "Write|Edit|MultiEdit",
    script: "plain-english-docs.sh",
    // Markdown only. Without this the hook fires on every source file the
    // session touches and discards the call after the fact.
    ifRule: "Write(*.md) or Edit(*.md) or MultiEdit(*.md) or Write(*.mdx) or Edit(*.mdx)",
  },
  {
    channel: "github",
    matcher: "Bash",
    script: "plain-english-github.sh",
    ifRule: undefined,
  },
  {
    channel: "issue",
    matcher: "mcp__linear__save_issue|mcp__linear__save_comment",
    script: "plain-english-issue.sh",
    ifRule: undefined,
  },
] as const;

/**
 * The two events that carry the assistant's final message.
 *
 * **Both take the nested `{ matcher, hooks }` shape**, and getting that wrong
 * is worse than it sounds. The documentation shows `Stop` flat, as a bare
 * `{ type, command }` in the event array. Written that way against 2.1.234 the
 * whole settings file fails validation, and `claude --help` says the rest out
 * loud: in print mode a settings file that fails validation is "silently
 * ignored (no error dialog is shown)". So one wrong entry here takes every
 * other hook in the user's file down with it, without a word.
 *
 * Observed, 2026-08-18, Claude Code 2.1.234: flat `Stop` fires nothing at all,
 * nested `Stop` fires and carries `last_assistant_message`. Every event in a
 * working settings file on this machine uses the nested shape, including the
 * ones the documentation shows flat.
 *
 * Sixty seconds, and the reason it is not ten is worth stating. A hook that
 * times out has its output thrown away, so a budget set too tight does not make
 * the gate quicker: it deletes the block and reports nothing. Almost every
 * reply is judged by counting, which is instant. The tenth that trips a limit
 * goes to a judge in print mode, and that takes seconds.
 *
 * `SubagentStop` is the one that matters most. An output style never reaches a
 * subagent, and this is the only mechanism in the package that does.
 */
const CHAT_SHIM = "plain-english-chat.sh";

function shim(channel: string): string {
  return `#!/usr/bin/env bash
# Generated by \`plain-english init\`. Thin shim: all logic lives in the package,
# so upstream fixes arrive with an npm update instead of a copy-paste.
# Fail-open by contract; the CLI never exits non-zero on this path.
exec npx --no-install plain-english hook ${channel} --agent claude-code
`;
}

export const claudeCode: AgentProfile = {
  id: "claude-code",
  label: "Claude Code",
  docs: "https://code.claude.com/docs/en/hooks",

  detect(raw) {
    return typeof raw["tool_name"] === "string" && !!process.env["CLAUDE_PROJECT_DIR"];
  },

  parse(raw): NormalisedEvent {
    const input = asRecord(raw["tool_input"]);
    const cwd = pick(raw, "cwd") || undefined;
    const filePath = pick(input, "file_path", "notebook_path");

    switch (pick(raw, "tool_name")) {
      case "Write":
        return { tool: "write", cwd, input: { filePath, content: pick(input, "content") } };
      case "Edit":
        // Only the inserted side.
        return { tool: "edit", cwd, input: { filePath, newString: pick(input, "new_string") } };
      case "MultiEdit":
        return {
          tool: "multi-edit",
          cwd,
          input: {
            filePath,
            edits: pickArray(input, "edits").map((e) => ({
              newString: pick(asRecord(e), "new_string"),
            })),
          },
        };
      case "Bash":
        return { tool: "bash", cwd, input: { command: pick(input, "command") } };
      default:
        // Includes the Linear-shaped MCP calls. The issue channel judges the
        // input directly, so it never needs the tool name.
        return { tool: "other", cwd, input: issueFields(input) };
    }
  },

  supportsAsk: true,

  emit(decision: Decision, event: HookEvent) {
    // Nothing on the post event. An agent that can surface `ask` to a human
    // before the write has already had its say, and repeating it afterwards
    // would report the same finding twice.
    if (event === "post") return { stdout: "", exitCode: 0 };
    // Writing nothing leaves the normal permission flow in charge, which is
    // what an allow means here.
    if (decision.allow) return { stdout: "", exitCode: 0 };
    return {
      stdout: JSON.stringify({
        hookSpecificOutput: {
          hookEventName: "PreToolUse",
          permissionDecision: decision.decision,
          permissionDecisionReason: decision.reason,
        },
      }),
      exitCode: 0,
    };
  },

  /**
   * Stop and SubagentStop.
   *
   * `decision: "block"` prevents the stop and shows `reason` to the model,
   * which then writes again. `systemMessage` reaches the user either way, and
   * is how the advisory tier says something without holding up a turn.
   */
  emitChat(decision: Decision) {
    if (decision.allow && !decision.advisory) return { stdout: "", exitCode: 0 };
    if (decision.allow) {
      return {
        stdout: JSON.stringify({ systemMessage: decision.advisory }),
        exitCode: 0,
      };
    }
    // Flat. The nested `hookSpecificOutput` shape shipped here until 0.11.0 and
    // could never hold a turn: observed 2026-08-18 against Claude Code 2.1.234
    // in a real interactive session, the nested body produced no second turn at
    // all while the flat one did. See the note on the wire-format test.
    //
    // `systemMessage` rides along so the reader sees why their turn paused
    // rather than watching the model write twice for no stated reason.
    return {
      stdout: JSON.stringify({
        decision: "block",
        reason: decision.reason,
        ...(decision.advisory ? { systemMessage: decision.advisory } : {}),
      }),
      exitCode: 0,
    };
  },

  plan(ctx: PlanContext) {
    return {
      config: [
        {
          path: ".claude/settings.json",
          at: ["hooks", "PreToolUse"],
          shape: "nested" as const,
          entries: CHANNELS.map((c) => ({
            matcher: c.matcher,
            hooks: [
              {
                type: "command",
                command: `$CLAUDE_PROJECT_DIR/.claude/hooks/${c.script}`,
                ...(c.ifRule ? { if: c.ifRule } : {}),
              },
              // The docs channel runs its semantic pass inside the command hook
              // above, behind a size guard, so it no longer needs a prompt hook.
              // A prompt hook hands the whole file to a model before any package
              // code runs, and a large one failed with `Prompt is too long`; the
              // command hook reads the payload first and declines the model call
              // when it is too large. The other channels carry a commit message
              // or an issue body, never a large file, and keep the prompt hook.
              ...(c.channel === "docs"
                ? []
                : [
                    {
                      type: "prompt" as const,
                      // Deliberately NOT the absolute path.
                      //
                      // .claude/settings.json is usually committed, so writing
                      // the machine's own directory layout into it breaks the
                      // file for every other contributor and leaks a local path
                      // into what may be a public repo. That is the same fault
                      // this package was built to remove.
                      //
                      // The prompt does not need the path anyway: the command
                      // hook scopes by path, and its `if` rule scopes by file
                      // type, both before the prompt is ever reached.
                      prompt: (ctx.prompts[c.channel] ?? "").replaceAll(
                        "{{PROJECT_DIR}}",
                        "this repository",
                      ),
                      model: ctx.model,
                      timeout: 30,
                      continueOnBlock: true,
                    },
                  ]),
            ],
          })),
        },
        {
          path: ".claude/settings.json",
          at: ["hooks", "Stop"],
          // Nested, not flat. See the note on CHAT_SHIM: flat is what the
          // documentation shows and what silently voids the file.
          shape: "nested" as const,
          entries: [
            {
              matcher: "*",
              hooks: [
                {
                  type: "command",
                  // 60, not 10. The deterministic pass is instant, but a
                  // failing reply limit sends the reply to a judge running in
                  // print mode, and that takes seconds. A hook that times out
                  // has its output discarded, so too short a timeout does not
                  // slow the gate down: it silently removes the block. That is
                  // the failure this package exists to catch, so it is not
                  // going to ship one.
                  timeout: 60,
                  command: `$CLAUDE_PROJECT_DIR/.claude/hooks/${CHAT_SHIM}`,
                },
              ],
            },
          ],
        },
        {
          path: ".claude/settings.json",
          at: ["hooks", "SubagentStop"],
          shape: "nested" as const,
          entries: [
            {
              matcher: "*",
              hooks: [
                {
                  type: "command",
                  // 60, not 10. The deterministic pass is instant, but a
                  // failing reply limit sends the reply to a judge running in
                  // print mode, and that takes seconds. A hook that times out
                  // has its output discarded, so too short a timeout does not
                  // slow the gate down: it silently removes the block. That is
                  // the failure this package exists to catch, so it is not
                  // going to ship one.
                  timeout: 60,
                  command: `$CLAUDE_PROJECT_DIR/.claude/hooks/${CHAT_SHIM}`,
                },
              ],
            },
          ],
        },
      ],
      shims: [
        ...CHANNELS.map((c) => ({
          path: `.claude/hooks/${c.script}`,
          body: shim(c.channel),
        })),
        { path: `.claude/hooks/${CHAT_SHIM}`, body: shim("chat") },
      ],
      // One file per level, all three installed. Switching between them is a
      // menu choice in /config rather than a re-install, which is the whole
      // reason they ship together.
      files: [
        ...(ctx.styles ?? []).map((s) => ({
          path: `.claude/output-styles/${s.path}`,
          body: s.body,
        })),
        // A skill sits beside the styles rather than replacing one. It loads
        // when the model reaches for it, so it costs nothing on the turns that
        // are not writing a document, and it does not compete for the single
        // output-style slot.
        ...(ctx.skills ?? []).map((s) => ({
          path: `.claude/skills/${s.path}`,
          body: s.body,
        })),
      ],
      // The file Claude Code's own picker writes. Setting it here is what makes
      // the style active without anybody selecting it; `init` prints the
      // previous value when it replaces one.
      settings: ctx.defaultStyle
        ? [
            {
              path: ".claude/settings.local.json",
              set: { outputStyle: ctx.defaultStyle.name },
            },
          ]
        : [],
      notes: [
        "The style takes effect on the next session. Run /clear, or start a new one.",
        "The writing-a-document skill loads on demand, so it costs nothing until a markdown file is being written. It does not replace the output style.",
        "Switch level under /config > Output style. The standalone /output-style command was removed in v2.1.91.",
        "A style reaches the main conversation and a fork, which inherits the parent's system prompt. It does not reach a subagent, which runs its own.",
        "The Stop and SubagentStop hooks cover what a style cannot. They hold a turn and send the finding back to be written again. To have them report without holding anything up, put chat.failOn: never in .plain-english.yml.",
      ],
    };
  },
};
