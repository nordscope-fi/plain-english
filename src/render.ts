/**
 * Generate every artifact that restates the rules.
 *
 * The old design maintained the same list in four shapes: a regex in three
 * shell scripts, a prose list inside three prompt bodies, a human-readable
 * table in a markdown file, and a summary in the project instructions. Nothing
 * checked that they agreed, and they did not.
 *
 * Here, only rules/default.yml is written by hand. Everything else is emitted
 * from it and checked by CI.
 */

